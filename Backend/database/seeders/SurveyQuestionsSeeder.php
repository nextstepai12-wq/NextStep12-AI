 * سييدر كامل لأسئلة استبيان الميول الأكاديمية، مبني على ملف
 * "بنك أسئلة لطلاب توجيه" (الإصدار 4.0 - Weighted Single-Select).
 *
 * ✅ هذا السييدر كامل: يحتوي على جميع الأسئلة الـ25 لكل عمادة (6 عمادات × 25 = 150 سؤال)
 *
 * ==============================================================================
 * قرارات مهمة:
 * ==============================================================================
 * 1) "العمادة" في ملف الورد = "الميول" (academic_interests)
 *
 * 2) الرمز العائلي (F1, F2, G1, M1, N1, S1, T-a...) يُخزن داخل
 *    survey_question_options.option_value كـ JSON.
 *
 * 3) خيارات الوزن المزدوج (Partial Cross-Loading) تُخزن كـ JSON في option_value:
 *    مثال: {"F3":2,"F5":1}
 *    weight_score: يخزن الوزن الأساسي (الأول المذكور) فقط.
 *
 * 4) خيارات "بدون نقاط" (0) — option_value = '{}'
 * ==============================================================================
 */
class SurveyQuestionsSeeder extends Seeder
{
    public function run(): void
    {
        $now = Carbon::now();

        // 1) تأكيد وجود "الميول"
        $interestNames = [
            'الهندسة والنظم الذكية',
            'تكنولوجيا المعلومات',
            'العلوم الإنسانية والإعلام',
            'إدارة المال والأعمال',
            'التمريض وعلوم الصحة',
            'التربية',
        ];

        $interestIds = [];
        foreach ($interestNames as $name) {
            $id = DB::table('academic_interests')->where('name', $name)->value('id');
            if (!$id) {
                $id = DB::table('academic_interests')->insertGetId([
                    'name'       => $name,
                    'is_active'  => true,
                    'created_at' => $now,
                    'updated_at' => $now,
                ]);
            }
            $interestIds[$name] = $id;
        }

        // 2) بنك الأسئلة الكامل
        $bank = $this->questionBank();
        $totalQuestions = 0;

        foreach ($bank as $interestName => $questions) {
            $interestId = $interestIds[$interestName];
            $orderIndex = 1;

            foreach ($questions as $q) {
                // منع التكرار
                $existingQuestionId = DB::table('survey_questions')
                    ->where('interest_id', $interestId)
                    ->where('question_text', $q['text'])
                    ->value('id');

                if ($existingQuestionId) {
                    $orderIndex++;
                    continue;
                }

                $questionId = DB::table('survey_questions')->insertGetId([
                    'question_text'      => $q['text'],
                    'type'                => 'multiple_choice',
                    'order_index'         => $orderIndex,
                    'min_score_required'  => null,
                    'interest_id'         => $interestId,
                    'is_active'           => true,
                    'created_at'          => $now,
                    'updated_at'          => $now,
                ]);

                foreach ($q['options'] as $opt) {
                    // الوزن الأساسي = أول وزن مذكور بالخيار (أو 0 لخيار "بدون نقاط")
                    $primaryWeight = 0;
                    foreach ($opt['weights'] as $w) {
                        $primaryWeight = $w;
                        break;
                    }

                    DB::table('survey_question_options')->insert([
                        'question_id'  => $questionId,
                        'option_text'  => $opt['text'],
                        'weight_score' => $primaryWeight,
                        'option_value' => json_encode($opt['weights'], JSON_UNESCAPED_UNICODE),
                        'created_at'   => $now,
                        'updated_at'   => $now,
                    ]);
                }

                $orderIndex++;
                $totalQuestions++;
            }
        }

        $this->command->info("تم إدخال {$totalQuestions} سؤال استبيان كامل (25 سؤال × 6 عمادات = 150 سؤال) بنجاح.");
    }

